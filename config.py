PINAKES_SUBDIR = "pinakes"    # πίνακες κατάταξης αναπληρωτών (ανά κλάδο)
MONIMOI_SUBDIR = "monimoi"    # αρχεία διορισμών / μονίμων
FASEIS_SUBDIR = "faseis"      # αρχεία ανά φάση πρόσληψης / σχολικό έτος
OUTPUT_SUBDIR = "output"      # εδώ γράφονται τα αποτελέσματα


def _sub(name: str) -> Path:
    """Επιστρέφει τον υποφάκελο αν υπάρχει, αλλιώς τον κεντρικό φάκελο."""
    p = DATA_DIR / name
    return p if p.is_dir() else DATA_DIR


def pinakes_dir() -> Path:
    return _sub(PINAKES_SUBDIR)


def monimoi_dir() -> Path:
    return _sub(MONIMOI_SUBDIR)


def faseis_dir() -> Path:
    """
    ΔΕΝ κάνει fallback στον κεντρικό φάκελο (σε αντίθεση με τα άλλα _sub()):
    οι φάσεις είναι ξεχωριστά αρχεία που πρέπει να μπουν σε δικό τους
    υποφάκελο, αλλιώς θα μπερδεύονταν με τους πίνακες κατάταξης.
    """
    return DATA_DIR / FASEIS_SUBDIR


def output_dir() -> Path:
    p = DATA_DIR / OUTPUT_SUBDIR
    p.mkdir(parents=True, exist_ok=True)
    return p


def output_dir_path() -> Path:
    """Ίδιο με output_dir() αλλά χωρίς να δημιουργεί τον φάκελο (για read-only χρήση)."""
    return DATA_DIR / OUTPUT_SUBDIR


